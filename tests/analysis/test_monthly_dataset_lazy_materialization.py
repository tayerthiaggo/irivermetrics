"""`_monthly_dataset()` / `section_compat_rows()` must not eagerly load the
whole `(time, y, x)` cube, and must not materialise `water` and `valid_obs`
as two separate top-level Dask computations.

Design note (W3.3, docs/superpowers/plans/2026-07-27-dea-zones-and-catchment-speed.md
section 3.3): the pre-fix code called ``da_feature.load()`` on the *entire*
feature cube (former ``compat.py:118``) and then ``valid_obs.astype(bool).load()``
separately (former ``compat.py:164``). The code comment claimed "section
clips are bounded" -- true only while this function was ever called on small
reach-scale clips. At catchment scale that same code is a guaranteed OOM: it
reads the full source array into memory (once per ``.load()`` call, i.e.
twice, sequentially) before any patch work starts.

Two independent proof mechanisms are used here:

1. **Dask top-level compute counter** (the primary, adversarial proof).
   ``xarray``'s Dask chunk manager
   (``xarray.namedarray.daskmanager.DaskManager.compute``) does
   ``from dask.array import compute; return compute(*data, **kwargs)``
   -- a *fresh, call-time* import, so patching the ``dask.array.compute``
   module attribute is visible to it. This gives a precise, load-bearing
   signal:
     - Two separate ``DataArray.load()`` calls (the pre-fix pattern) each
       trigger their own ``dask.array.compute(single_array)`` call --
       TWO separate invocations, one array each.
     - A single fused ``xr.Dataset({"water": ..., "valid_obs": ...}).compute()``
       (the brief's specified fix) triggers exactly ONE
       ``dask.array.compute(water_array, valid_obs_array)`` invocation with
       BOTH arrays together.
   This is verified directly against real dask/xarray behavior (see the
   investigation in this task's report) before being relied on here, so the
   test is not guessing about dask internals.

2. **Source-chunk read counter** (proves Step 3: reads scale with the
   selected/bounded input, not a larger notional full-AOI extent). Each
   source array's chunks are generated by an instrumented
   ``dask.array.map_blocks`` function that counts real invocations
   (excluding the one-off zero-sized meta-inference probe dask issues at
   graph-construction time).

Both proof mechanisms are written to FAIL against the pre-fix implementation
and PASS only once ``water`` and ``valid_obs`` are materialised together in
one fused ``xr.Dataset({...}).compute()`` call, per the brief.
"""

