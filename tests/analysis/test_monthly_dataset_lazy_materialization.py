class _DaskComputeCallCounter:
    """Patches ``dask.array.compute`` to record each top-level invocation.

    ``calls`` is a list of ints: the number of Dask-backed arrays passed to
    each ``dask.array.compute(...)`` call. Two separate ``.load()`` calls on
    ``water`` and ``valid_obs`` show up as ``[1, 1]``; one fused
    ``xr.Dataset({"water": ..., "valid_obs": ...}).compute()`` shows up as
    ``[2]``. This distinguishes the pre-fix "materialise separately" pattern
    from the post-fix "materialise together" pattern precisely because
    xarray's Dask chunk manager resolves ``dask.array.compute`` via a
    call-time ``from dask.array import compute``, so patching the module
    attribute here is actually observed by xarray's load/compute path.
    """

    def __init__(self) -> None:
        self.calls: list[int] = []
        self._real_compute = da.compute
        self._patcher = mock.patch.object(
            da, "compute", side_effect=self._counting_compute
        )

    def _counting_compute(self, *args, **kwargs):
        self.calls.append(len(args))
        return self._real_compute(*args, **kwargs)

    def __enter__(self) -> "_DaskComputeCallCounter":
        self._patcher.start()
        return self

    def __exit__(self, *exc_info) -> None:
        self._patcher.stop()

    @property
    def n_top_level_computes(self) -> int:
        return len(self.calls)

    @property
    def max_arrays_in_single_call(self) -> int:
        return max(self.calls, default=0)


def _counting_source(shape, *, chunks, seed, fill="random"):
    """Build a Dask array whose per-chunk generator is call-counted.

    Returns ``(dask_array, counter)`` where ``counter`` is a mutable dict
    with key ``"n_calls"`` (real chunk reads) and ``"shapes"`` (block shapes
    seen). Dask probes the block function once at graph-construction time
    with ``block_info=None`` for dtype/meta inference; that probe is
    construction noise, not a real read, so the counter is reset to 0 right
    after construction -- callers only see calls made during actual
    materialization (``.load()``/``.compute()``).
    """
    counter = {"n_calls": 0, "shapes": []}
    rng = np.random.default_rng(seed)

    def _block_fn(block_info=None):
        if block_info is None:
            return np.zeros((0,) * len(shape), dtype="int8")
        counter["n_calls"] += 1
        loc = block_info[None]["array-location"]
        block_shape = tuple(hi - lo for lo, hi in loc)
        counter["shapes"].append(block_shape)
        if fill == "ones":
            return np.ones(block_shape, dtype="int8")
        return (rng.random(block_shape) < 0.3).astype("int8")

    chunk_spec = tuple(
        tuple(_chunk_sizes(dim_size, chunk_size))
        for dim_size, chunk_size in zip(shape, chunks)
    )
    darr = da.map_blocks(_block_fn, dtype="int8", chunks=chunk_spec)
    counter["n_calls"] = 0  # discard the construction-time meta probe
    counter["shapes"] = []
    return darr, counter


def _chunk_sizes(dim_size: int, chunk_size: int) -> list[int]:
    sizes = [chunk_size] * (dim_size // chunk_size)
    remainder = dim_size % chunk_size
    if remainder:
        sizes.append(remainder)
    return sizes


def _coords(n_time: int, n_y: int, n_x: int):
    # n_time may exceed 12; encode months as sequential calendar months
    # wrapping year boundaries rather than a fixed "2020-{m:02d}" pattern,
    # so large n_time (OOM-regression test) does not overflow month 12.
    times = (
        np.datetime64("2000-01", "M") + np.arange(n_time)
    ).astype("datetime64[ns]")
    ys = np.arange(n_y, dtype=float) * -30.0
    xs = np.arange(n_x, dtype=float) * 30.0
    return {"time": times, "y": ys, "x": xs}


def _make_counting_cube(*, n_time, n_y, n_x, chunks, seed, fill="random"):
    darr, counter = _counting_source(
        (n_time, n_y, n_x), chunks=chunks, seed=seed, fill=fill
    )
    cube = xr.DataArray(
        darr, dims=("time", "y", "x"), coords=_coords(n_time, n_y, n_x)
    )
    return cube, counter


