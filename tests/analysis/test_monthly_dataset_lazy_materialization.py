def test_source_reads_scale_with_selected_region_not_full_array():
    """Reads must scale with the bounded input actually passed in, not with
    some larger notional full-AOI/full-cube extent.

    Builds two synthetic cubes of the SAME per-chunk shape but different
    extents (a small "selected window" cube and a much larger "full AOI"
    cube), and asserts the number of source-chunk reads for the small cube
    is strictly less than for the large cube, and exactly equal to its own
    chunk count -- i.e. `_monthly_dataset` never touches more chunks than
    the array it was actually given.
    """
    small, small_counter = _make_counting_cube(
        n_time=1, n_y=8, n_x=8, chunks=(1, 4, 4), seed=3
    )
    large, large_counter = _make_counting_cube(
        n_time=1, n_y=64, n_x=64, chunks=(1, 4, 4), seed=3
    )

    small_chunks = small.data.npartitions
    large_chunks = large.data.npartitions
    assert small_chunks < large_chunks, "test fixture setup error"

    _monthly_dataset(small)
    _monthly_dataset(large)

    assert small_counter["n_calls"] == small_chunks
    assert large_counter["n_calls"] == large_chunks
    assert small_counter["n_calls"] < large_counter["n_calls"], (
        "expected the smaller bounded region to touch fewer source chunks "
        f"than the larger one; got small={small_counter['n_calls']} "
        f"large={large_counter['n_calls']}"
    )


