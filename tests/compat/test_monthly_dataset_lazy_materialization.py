def test_monthly_dataset_fused_output_matches_eager_reference():
    """Output-parity: fused-compute `_monthly_dataset` produces byte-identical
    `water`/`valid_obs` values to a plain eager (non-Dask) reference build,
    for the same input data.
    """
    n_time, n_y, n_x = 3, 10, 10
    rng = np.random.default_rng(42)
    backing = (rng.random((n_time, n_y, n_x)) < 0.4).astype("int8")
    coords = _coords(n_time, n_y, n_x)

    eager_feature = xr.DataArray(
        backing.copy(), dims=("time", "y", "x"), coords=coords
    )
    eager_monthly = _monthly_dataset(eager_feature)

    lazy_feature = xr.DataArray(
        da.from_array(backing.copy(), chunks=(1, 5, 5), name=False),
        dims=("time", "y", "x"),
        coords=coords,
    )
    lazy_monthly = _monthly_dataset(lazy_feature)

    np.testing.assert_array_equal(
        eager_monthly["water"].values, lazy_monthly["water"].values
    )
    np.testing.assert_array_equal(
        eager_monthly["valid_obs"].values, lazy_monthly["valid_obs"].values
    )


def test_monthly_dataset_oom_regression_large_cube_bounded_by_chunk():
    """OOM-regression proof: a cube far larger than the earlier small tests
    must still show the same 1:1 chunk-count-to-read-count relationship (no
    quadratic/duplicate blowup as size grows), pinning that
    `_monthly_dataset` never needs to instantiate more than its own bounded
    input regardless of how large that input's grid gets.
    """
    n_time, n_y, n_x = 8, 256, 256
    cube, counter = _make_counting_cube(
        n_time=n_time, n_y=n_y, n_x=n_x, chunks=(1, 64, 64), seed=9
    )
    expected_chunks = cube.data.npartitions

    monthly = _monthly_dataset(cube)

    assert counter["n_calls"] == expected_chunks
    assert monthly["water"].shape == (n_time, n_y, n_x)


def test_section_compat_rows_output_byte_identical_lazy_vs_eager():
    """End-to-end output parity: `section_compat_rows` on a Dask-backed
    input must produce byte-identical rows to the same input built eagerly
    (plain numpy), proving the lazy-materialization fix changes only HOW/WHEN
    data is realised, never the metric values themselves.
    """
    n_time, n_y, n_x = 4, 12, 12
    rng = np.random.default_rng(123)
    water = (rng.random((n_time, n_y, n_x)) < 0.35).astype("int8")
    valid = np.ones((n_time, n_y, n_x), dtype=bool)
    coords = _coords(n_time, n_y, n_x)

    config = _config()
    pixel_size_m = 30.0
    section_area_km2 = float(n_y * n_x) * pixel_size_m**2 / 1_000_000.0
    selected_ids = {
        "number_of_pools",
        "lpi",
        "awre",
        "awmsi",
        "occurrence",
        "refuge_area",
        "apsec",
    }

    eager_feature = xr.DataArray(water.copy(), dims=("time", "y", "x"), coords=coords)
    eager_valid = xr.DataArray(valid.copy(), dims=("time", "y", "x"), coords=coords)
    eager_rows = section_compat_rows(
        eager_feature,
        section="AOI",
        section_area_km2=section_area_km2,
        pixel_size_m=pixel_size_m,
        config=config,
        valid_obs=eager_valid,
        selected_ids=selected_ids,
    )

    lazy_feature = xr.DataArray(
        da.from_array(water.copy(), chunks=(1, 6, 6), name=False),
        dims=("time", "y", "x"),
        coords=coords,
    )
    lazy_valid = xr.DataArray(
        da.from_array(valid.copy(), chunks=(1, 6, 6), name=False),
        dims=("time", "y", "x"),
        coords=coords,
    )
    lazy_rows = section_compat_rows(
        lazy_feature,
        section="AOI",
        section_area_km2=section_area_km2,
        pixel_size_m=pixel_size_m,
        config=config,
        valid_obs=lazy_valid,
        selected_ids=selected_ids,
    )

    assert len(eager_rows) == len(lazy_rows) == n_time
    for eager_row, lazy_row in zip(eager_rows, lazy_rows):
        assert eager_row.keys() == lazy_row.keys()
        for key in eager_row:
            eager_value = eager_row[key]
            lazy_value = lazy_row[key]
            if isinstance(eager_value, float) and np.isnan(eager_value):
                assert isinstance(lazy_value, float) and np.isnan(lazy_value)
            else:
                assert eager_value == lazy_value, (
                    f"mismatch at key={key!r}: eager={eager_value!r} "
                    f"lazy={lazy_value!r}"
                )
